"""Reconcile workbook WBS codes with the application's existing catalogue."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
import re
from typing import Any

import networkx as nx

from .graph_loader import (
    DEFAULT_WORKBOOK,
    WorkbookError,
    find_table,
    load_knowledge_graph,
    read_workbook,
)

DEFAULT_APP_SOURCE = Path(__file__).resolve().parents[1] / "refine.js"
_WBS_CALL = re.compile(
    r"""\bW\(\s*['"]([A-Z]{2,3}-\d{2})['"]\s*,\s*['"]([^'"]*)['"]"""
)
_ID_FACTORY = re.compile(
    r"""id\s*:\s*`([^`$]*)\$\{\s*code\.toLowerCase\(\)\.replaceAll\(\s*['"]([^'"]+)['"]\s*,\s*['"]([^'"]*)['"]\s*\)\s*\}"""
)


@dataclass(frozen=True)
class ActivityMapping:
    wbs_code: str
    browser_id: str | None
    workbook_browser_id: str | None
    activity_name: str
    catalogue_name: str | None
    match_status: str | None


@dataclass
class ActivityMappingReport:
    entries: dict[str, ActivityMapping] = field(default_factory=dict)
    issues: list[dict[str, Any]] = field(default_factory=list)

    @property
    def mapping(self) -> dict[str, str]:
        return {
            code: entry.browser_id
            for code, entry in self.entries.items()
            if entry.browser_id is not None
        }

    @property
    def missing_codes(self) -> list[str]:
        return sorted(
            code for code, entry in self.entries.items() if not entry.browser_id
        )


def build_activity_mapping(
    workbook_path: str | Path = DEFAULT_WORKBOOK,
    application_source_path: str | Path = DEFAULT_APP_SOURCE,
) -> ActivityMappingReport:
    """Map all workbook activity codes to IDs generated by the current app.

    The application source is read-only. IDs are derived from its existing
    catalogue ID factory and checked against the workbook's WBS_Code_Map.
    """
    workbook = read_workbook(workbook_path)
    activities = find_table(workbook, "activities")
    workbook_map = find_table(workbook, "activity_map")
    report = ActivityMappingReport()
    if activities is None:
        report.issues.append(
            {"issue": "missing_activity_catalogue", "source": str(workbook_path)}
        )
        return report
    if workbook_map is None:
        report.issues.append(
            {"issue": "missing_wbs_code_map", "source": str(workbook_path)}
        )
        return report

    source_path = Path(application_source_path).expanduser().resolve()
    try:
        source = source_path.read_text(encoding="utf-8")
    except OSError as error:
        report.issues.append(
            {
                "issue": "application_catalogue_unavailable",
                "path": str(source_path),
                "detail": str(error),
            }
        )
        source = ""

    id_factory = _ID_FACTORY.search(source)
    if id_factory is None:
        report.issues.append(
            {
                "issue": "application_id_factory_not_recognized",
                "path": str(source_path),
            }
        )
        id_prefix = separator = replacement = None
    else:
        id_prefix, separator, replacement = id_factory.groups()

    catalogue: dict[str, str] = {}
    for code, name in _WBS_CALL.findall(source):
        canonical_code = code.upper()
        if canonical_code in catalogue:
            report.issues.append(
                {"issue": "duplicate_code_in_application_catalogue", "code": canonical_code}
            )
        else:
            catalogue[canonical_code] = name.strip()

    workbook_records: dict[str, dict[str, Any]] = {}
    for row_number, row in zip(activities.row_numbers, activities.rows):
        code = str(row.get("WBS code", "")).strip().upper()
        if not code:
            report.issues.append(
                {
                    "issue": "activity_missing_wbs_code",
                    "sheet": activities.sheet_name,
                    "row": row_number,
                }
            )
            continue
        if code in workbook_records:
            report.issues.append(
                {
                    "issue": "duplicate_code_in_workbook_catalogue",
                    "code": code,
                    "sheet": activities.sheet_name,
                    "row": row_number,
                }
            )
        else:
            workbook_records[code] = row

    mappings_by_code: dict[str, dict[str, Any]] = {}
    for row_number, row in zip(workbook_map.row_numbers, workbook_map.rows):
        code = str(row.get("WBS_code", "")).strip().upper()
        if not code:
            report.issues.append(
                {
                    "issue": "mapping_missing_wbs_code",
                    "sheet": workbook_map.sheet_name,
                    "row": row_number,
                }
            )
            continue
        if code in mappings_by_code:
            report.issues.append(
                {
                    "issue": "duplicate_code_in_wbs_code_map",
                    "code": code,
                    "sheet": workbook_map.sheet_name,
                    "row": row_number,
                }
            )
        else:
            mappings_by_code[code] = row

    for code, row in workbook_records.items():
        map_row = mappings_by_code.get(code)
        workbook_id = (
            str(map_row.get("Browser_ID", "")).strip() if map_row else ""
        ) or None
        catalogue_name = catalogue.get(code)
        browser_id = None
        if catalogue_name is not None and id_prefix is not None:
            browser_id = (
                f"{id_prefix}{code.lower().replace(separator, replacement)}"
            )
        entry = ActivityMapping(
            wbs_code=code,
            browser_id=browser_id,
            workbook_browser_id=workbook_id,
            activity_name=str(row.get("Activity name", "")).strip(),
            catalogue_name=catalogue_name,
            match_status=(
                str(map_row.get("Match_status", "")).strip() if map_row else None
            ),
        )
        report.entries[code] = entry

        if map_row is None or workbook_id is None:
            report.issues.append({"issue": "missing_workbook_mapping", "code": code})
        if catalogue_name is None:
            report.issues.append(
                {"issue": "missing_activity_in_application_catalogue", "code": code}
            )
        if browser_id and workbook_id and browser_id != workbook_id:
            report.issues.append(
                {
                    "issue": "browser_id_mismatch",
                    "code": code,
                    "workbook_browser_id": workbook_id,
                    "application_browser_id": browser_id,
                }
            )
        if catalogue_name and entry.activity_name.casefold() != catalogue_name.casefold():
            report.issues.append(
                {
                    "issue": "activity_name_mismatch",
                    "code": code,
                    "workbook_name": entry.activity_name,
                    "application_name": catalogue_name,
                }
            )

    for code in sorted(set(mappings_by_code) - set(workbook_records)):
        report.issues.append({"issue": "mapping_without_catalogue_activity", "code": code})
    for code in sorted(set(catalogue) - set(workbook_records)):
        report.issues.append(
            {"issue": "application_activity_without_workbook_record", "code": code}
        )

    return report


def _node_result(graph: nx.MultiDiGraph, node_id: str) -> dict[str, Any]:
    attributes = graph.nodes[node_id]
    return {
        "id": node_id,
        "label": attributes.get("label", node_id),
        "node_type": attributes.get("node_type"),
        "record": dict(attributes.get("record", {})),
        "source_ids": list(attributes.get("source_ids", ())),
        "evidence_category": attributes.get("evidence_category"),
        "evidence_status": attributes.get("evidence_status"),
    }


def _unique_records(
    graph: nx.MultiDiGraph,
    ids_and_relations: dict[str, set[str]],
) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for node_id in sorted(ids_and_relations):
        if not graph.has_node(node_id) or not graph.nodes[node_id].get("defined"):
            continue
        item = _node_result(graph, node_id)
        item["relationship_types"] = sorted(ids_and_relations[node_id])
        records.append(item)
    return records


def _add_id(
    destination: dict[str, set[str]], node_id: str, relationship: str
) -> None:
    destination.setdefault(node_id, set()).add(relationship)


def get_activity_knowledge(
    wbs_code: str,
    graph: nx.MultiDiGraph | None = None,
    workbook_path: str | Path = DEFAULT_WORKBOOK,
) -> dict[str, Any]:
    """Return only workbook-supported knowledge paths for a canonical WBS code."""
    graph = graph if graph is not None else load_knowledge_graph(workbook_path)
    code = str(wbs_code).strip().upper()
    if not graph.has_node(code) or graph.nodes[code].get("node_type") != "construction_activity":
        raise KeyError(f"Unknown canonical WBS activity code: {wbs_code!r}")

    hazards: dict[str, set[str]] = {}
    exposures: dict[str, set[str]] = {}
    controls: dict[str, set[str]] = {}
    interventions: dict[str, set[str]] = {}
    consequences: dict[str, set[str]] = {}
    evidence_ids: set[str] = set()
    link_nodes: list[str] = []
    consequence_text: dict[tuple[str, str], dict[str, Any]] = {}

    activity = graph.nodes[code]
    evidence_ids.update(activity.get("source_ids", ()))

    for _, hazard_id, _, edge in graph.out_edges(code, keys=True, data=True):
        predicate = edge.get("predicate")
        if predicate == "mayExperience":
            _add_id(hazards, hazard_id, predicate)

    for link_id, _, _, edge in graph.in_edges(code, keys=True, data=True):
        if edge.get("relationship_type") != "links_activity":
            continue
        if graph.nodes[link_id].get("node_type") != "activity_hazard_link":
            continue
        link_nodes.append(link_id)
        link = graph.nodes[link_id]
        evidence_ids.update(link.get("source_ids", ()))
        for _, target, _, relationship in graph.out_edges(
            link_id, keys=True, data=True
        ):
            relation_type = relationship.get("relationship_type", "")
            if relation_type == "links_hazard":
                _add_id(hazards, target, relation_type)
            elif relation_type == "declares_exposure_condition":
                _add_id(exposures, target, relation_type)
            elif relation_type == "candidate_control":
                _add_id(controls, target, relation_type)
            elif relation_type == "candidate_intervention":
                _add_id(interventions, target, relation_type)
            elif relation_type == "identifies_mechanism":
                mechanism = graph.nodes.get(target, {})
                evidence_ids.update(mechanism.get("source_ids", ()))
            evidence_ids.update(relationship.get("source_ids", ()))

        for field_name, kind in (
            ("Potential injury / ill-health", "safety"),
            ("Potential operational consequence", "performance"),
        ):
            text = str(link.get("record", {}).get(field_name, "")).strip()
            if text:
                consequence_text[(kind, text)] = {
                    "id": None,
                    "kind": kind,
                    "label": text,
                    "source_link_id": link_id,
                    "evidence_status": link.get("evidence_status"),
                    "source_ids": list(link.get("source_ids", ())),
                }

    for hazard_id in list(hazards):
        if not graph.has_node(hazard_id):
            continue
        hazard = graph.nodes[hazard_id]
        evidence_ids.update(hazard.get("source_ids", ()))
        for _, consequence_id, _, edge in graph.out_edges(
            hazard_id, keys=True, data=True
        ):
            predicate = edge.get("predicate", "")
            if predicate in {
                "mayResultInSafetyConsequence",
                "mayResultInPerformanceConsequence",
            }:
                _add_id(consequences, consequence_id, predicate)
            evidence_ids.update(edge.get("source_ids", ()))
        for control_id, _, _, edge in graph.in_edges(
            hazard_id, keys=True, data=True
        ):
            if edge.get("predicate") != "mitigates":
                continue
            node_type = graph.nodes[control_id].get("node_type")
            if node_type == "control_measure":
                _add_id(controls, control_id, "mitigates")
            elif node_type == "resilience_intervention":
                _add_id(interventions, control_id, "mitigates")
            evidence_ids.update(edge.get("source_ids", ()))

    for destination in (controls, interventions, consequences, exposures):
        for node_id in destination:
            if graph.has_node(node_id):
                evidence_ids.update(graph.nodes[node_id].get("source_ids", ()))

    evidence: list[dict[str, Any]] = []
    for source_id in sorted(evidence_ids):
        if graph.has_node(source_id) and graph.nodes[source_id].get("node_type") == "evidence_source":
            evidence.append(_node_result(graph, source_id))

    assessment_records = [
        dict(record)
        for record in graph.graph.get("project_specific_wsh_assessment_records", ())
        if str(record.get("wbs_code", "")).strip().upper() == code
    ]
    approved_assessments = [
        dict(record)
        for record in graph.graph.get("approved_wsh_assessment_records", ())
        if str(record.get("wbs_code", "")).strip().upper() == code
    ]

    return {
        "wbs_code": code,
        "application_id": activity.get("browser_id"),
        "activity": _node_result(graph, code),
        "hazards": _unique_records(graph, hazards),
        "consequences": _unique_records(graph, consequences)
        + [consequence_text[key] for key in sorted(consequence_text)],
        "exposure_conditions": _unique_records(graph, exposures),
        "controls": _unique_records(graph, controls),
        "interventions": _unique_records(graph, interventions),
        "evidence": evidence,
        "activity_hazard_link_ids": sorted(link_nodes),
        "wsh_assessment_records": assessment_records,
        "approved_wsh_assessments": approved_assessments,
    }
